/**
 * Dynamic Maintenance Checklist Component
 * 
 * Generates equipment-specific maintenance checklists using AI
 */

import React, { useState } from 'react';
import { Wrench, X, Loader2, Download, CheckSquare, AlertTriangle, Clock } from 'lucide-react';
import axios from 'axios';

interface MaintenanceTask {
  step: number;
  task: string;
  frequency: string;
  safety_notes: string;
}

interface MaintenanceChecklistData {
  equipment_type: string;
  equipment_tag: string;
  checklist_title: string;
  tasks: MaintenanceTask[];
  safety_warnings: string[];
  estimated_time: string;
}

interface MaintenanceChecklistProps {
  equipmentType: string;
  equipmentTag: string;
  equipmentDescription?: string;
  onClose: () => void;
}

export const MaintenanceChecklist: React.FC<MaintenanceChecklistProps> = ({
  equipmentType,
  equipmentTag,
  equipmentDescription = '',
  onClose,
}) => {
  const [checklist, setChecklist] = useState<MaintenanceChecklistData | null>(null);
  const [isGenerating, setIsGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Auto-generate on mount
  React.useEffect(() => {
    generateChecklist();
  }, []);

  const generateChecklist = async () => {
    setIsGenerating(true);
    setError(null);

    try {
      const response = await axios.post<MaintenanceChecklistData>(
        'http://localhost:8000/api/generate-maintenance-checklist',
        {
          equipment_type: equipmentType,
          equipment_tag: equipmentTag,
          equipment_description: equipmentDescription,
        }
      );

      setChecklist(response.data);
    } catch (err: any) {
      console.error('Maintenance checklist generation failed:', err);
      
      let errorMessage = 'Failed to generate maintenance checklist.';
      
      if (err.response?.status === 503) {
        errorMessage = 'Backend service unavailable. Make sure the backend is running and Gemini API is configured.';
      } else if (err.response?.status === 500) {
        errorMessage = 'Backend error occurred. Check backend logs for details.';
      } else if (err.code === 'ERR_NETWORK') {
        errorMessage = 'Cannot connect to backend. Make sure it\'s running on http://localhost:8000';
      }
      
      setError(errorMessage);
    } finally {
      setIsGenerating(false);
    }
  };

  const handleExport = () => {
    if (!checklist) return;

    // Generate text content
    let content = `${checklist.checklist_title}\n`;
    content += `${'='.repeat(checklist.checklist_title.length)}\n\n`;
    content += `Equipment: ${checklist.equipment_type}\n`;
    content += `Tag: ${checklist.equipment_tag}\n`;
    content += `Estimated Time: ${checklist.estimated_time}\n\n`;
    
    content += `SAFETY WARNINGS:\n`;
    content += `${'-'.repeat(50)}\n`;
    checklist.safety_warnings.forEach((warning, idx) => {
      content += `${idx + 1}. ${warning}\n`;
    });
    
    content += `\n\nMAINTENANCE TASKS:\n`;
    content += `${'-'.repeat(50)}\n\n`;
    
    checklist.tasks.forEach((task) => {
      content += `Step ${task.step}: ${task.task}\n`;
      content += `Frequency: ${task.frequency}\n`;
      if (task.safety_notes) {
        content += `Safety: ${task.safety_notes}\n`;
      }
      content += `\n`;
    });
    
    content += `\n${'='.repeat(50)}\n`;
    content += `Generated by EDAI4 - P&ID Intelligence System\n`;
    content += `Date: ${new Date().toLocaleString()}\n`;

    // Download as text file
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `maintenance_checklist_${equipmentTag.replace(/[^a-zA-Z0-9]/g, '_')}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const getFrequencyColor = (frequency: string) => {
    const freq = frequency.toLowerCase();
    if (freq.includes('daily')) return 'text-red-400 bg-red-500/10 border-red-500/30';
    if (freq.includes('weekly')) return 'text-orange-400 bg-orange-500/10 border-orange-500/30';
    if (freq.includes('monthly')) return 'text-yellow-400 bg-yellow-500/10 border-yellow-500/30';
    if (freq.includes('quarterly')) return 'text-blue-400 bg-blue-500/10 border-blue-500/30';
    if (freq.includes('annual')) return 'text-green-400 bg-green-500/10 border-green-500/30';
    return 'text-industrial-400 bg-industrial-700/50 border-industrial-600';
  };

  return (
    <div className="fixed inset-0 bg-black/60 backdrop-blur-sm z-50 flex items-center justify-center p-6">
      <div className="bg-industrial-900 border-2 border-accent-blue rounded-lg shadow-2xl shadow-accent-blue/20 w-full max-w-3xl max-h-[90vh] overflow-hidden flex flex-col">
        {/* Header */}
        <div className="bg-gradient-to-r from-accent-blue to-accent-cyan px-6 py-4 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <Wrench className="w-6 h-6 text-industrial-950" />
            <div>
              <h2 className="text-xl font-bold text-industrial-950">Maintenance Checklist</h2>
              <p className="text-sm text-industrial-950/70 font-mono">
                {equipmentType} - {equipmentTag}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 hover:bg-industrial-950/20 rounded-lg transition-colors"
          >
            <X className="w-5 h-5 text-industrial-950" />
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-6">
          {isGenerating && (
            <div className="flex flex-col items-center justify-center py-12">
              <Loader2 className="w-12 h-12 text-accent-blue animate-spin mb-4" />
              <p className="text-industrial-300 font-medium">Generating maintenance checklist...</p>
              <p className="text-industrial-500 text-sm mt-2">Using AI to create equipment-specific tasks</p>
            </div>
          )}

          {error && (
            <div className="bg-red-500/10 border border-red-500 rounded-lg p-4">
              <div className="flex items-start gap-3">
                <AlertTriangle className="w-5 h-5 text-red-400 mt-0.5 flex-shrink-0" />
                <div className="flex-1">
                  <p className="text-red-400 font-medium mb-1">Error</p>
                  <p className="text-sm text-red-300">{error}</p>
                  <button
                    onClick={generateChecklist}
                    className="mt-3 px-4 py-2 bg-red-500 hover:bg-red-600 text-white rounded-lg text-sm font-medium transition-colors"
                  >
                    Retry
                  </button>
                </div>
              </div>
            </div>
          )}

          {checklist && (
            <div className="space-y-6">
              {/* Estimated Time */}
              <div className="flex items-center gap-2 text-industrial-300">
                <Clock className="w-4 h-4 text-accent-blue" />
                <span className="text-sm">
                  <span className="font-semibold">Estimated Time:</span> {checklist.estimated_time}
                </span>
              </div>

              {/* Safety Warnings */}
              <div className="bg-red-500/10 border-2 border-red-500 rounded-lg p-4">
                <div className="flex items-center gap-2 mb-3">
                  <AlertTriangle className="w-5 h-5 text-red-400" />
                  <h3 className="text-lg font-bold text-red-400 uppercase tracking-wide">
                    Safety Warnings
                  </h3>
                </div>
                <ul className="space-y-2">
                  {checklist.safety_warnings.map((warning, idx) => (
                    <li key={idx} className="flex items-start gap-2 text-sm text-red-300">
                      <span className="text-red-400 font-bold mt-0.5">⚠</span>
                      <span>{warning}</span>
                    </li>
                  ))}
                </ul>
              </div>

              {/* Maintenance Tasks */}
              <div>
                <h3 className="text-lg font-bold text-industrial-100 mb-4 flex items-center gap-2">
                  <CheckSquare className="w-5 h-5 text-accent-blue" />
                  Maintenance Tasks
                </h3>
                <div className="space-y-4">
                  {checklist.tasks.map((task) => (
                    <div
                      key={task.step}
                      className="bg-industrial-800 border border-industrial-600 rounded-lg p-4 hover:border-accent-blue/50 transition-colors"
                    >
                      <div className="flex items-start gap-3">
                        <div className="flex-shrink-0 w-8 h-8 bg-accent-blue rounded-full flex items-center justify-center text-industrial-950 font-bold">
                          {task.step}
                        </div>
                        <div className="flex-1">
                          <p className="text-industrial-100 font-medium mb-2">{task.task}</p>
                          
                          <div className="flex flex-wrap gap-2 items-center">
                            <span
                              className={`px-3 py-1 rounded-full text-xs font-semibold border ${getFrequencyColor(
                                task.frequency
                              )}`}
                            >
                              {task.frequency}
                            </span>
                            
                            {task.safety_notes && (
                              <div className="flex items-start gap-1 text-xs text-yellow-400 bg-yellow-500/10 px-2 py-1 rounded border border-yellow-500/30">
                                <AlertTriangle className="w-3 h-3 mt-0.5 flex-shrink-0" />
                                <span>{task.safety_notes}</span>
                              </div>
                            )}
                          </div>
                        </div>
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            </div>
          )}
        </div>

        {/* Footer */}
        {checklist && (
          <div className="border-t border-industrial-700 px-6 py-4 bg-industrial-800 flex items-center justify-between">
            <p className="text-xs text-industrial-500">
              Generated by AI • Review with qualified personnel before use
            </p>
            <div className="flex gap-2">
              <button
                onClick={handleExport}
                className="px-4 py-2 bg-accent-blue hover:bg-accent-blue/80 text-industrial-950 font-medium rounded-lg transition-colors flex items-center gap-2"
              >
                <Download className="w-4 h-4" />
                Export
              </button>
              <button
                onClick={onClose}
                className="px-4 py-2 bg-industrial-700 hover:bg-industrial-600 text-industrial-100 font-medium rounded-lg transition-colors"
              >
                Close
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};

export default MaintenanceChecklist;
